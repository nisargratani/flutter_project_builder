''';

  /// `test/core/utils/validators_test.dart`.
  static String validatorsTest(String package) => '''
$header
import 'package:flutter_test/flutter_test.dart';

import 'package:$package/core/extensions/string_extensions.dart';
import 'package:$package/core/utils/validators.dart';

void main() {
  group('Validators.email', () {
    test('accepts valid addresses', () {
      for (final email in [
        'john@example.com',
        'first.last+tag@sub.example.co.uk',
        'dev_1@example.museum',
      ]) {
        expect(Validators.email(email), isNull, reason: email);
        expect(email.isValidEmail, isTrue, reason: email);
      }
    });

    test('rejects invalid addresses', () {
      for (final email in ['plainaddress', 'a@b', '@example.com', 'a@.com']) {
        expect(Validators.email(email), isNotNull, reason: email);
        expect(email.isValidEmail, isFalse, reason: email);
      }
    });

    test('requires a value', () {
      expect(Validators.email(''), isNotNull);
      expect(Validators.email(null), isNotNull);
    });
  });

  test('Validators.required', () {
    expect(Validators.required('  '), isNotNull);
    expect(Validators.required('x'), isNull);
  });
}
''';

  /// `test/features/counter/counter_notifier_test.dart`.
  static String counterTest(String package) => '''
$header
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';

import 'package:$package/features/counter/presentation/providers/counter_provider.dart';

void main() {
  test('CounterNotifier increments, decrements and resets', () {
    final container = ProviderContainer();
    addTearDown(container.dispose);
    final notifier = container.read(counterProvider.notifier);

    expect(container.read(counterProvider).value, 0);
    notifier
      ..increment()
      ..increment()
      ..decrement();
    expect(container.read(counterProvider).value, 1);
    notifier.reset();
    expect(container.read(counterProvider).value, 0);
  });
}
''';

  /// `test/features/users/users_notifier_test.dart`.
  static String usersTest(String package) => '''
$header
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';

import 'package:$package/core/errors/app_exception.dart';
import 'package:$package/core/errors/failure.dart';
import 'package:$package/features/users/data/datasource/user_remote_data_source.dart';
import 'package:$package/features/users/data/models/user_model.dart';
import 'package:$package/features/users/presentation/providers/users_provider.dart';

class _FakeDataSource implements UserRemoteDataSource {
  _FakeDataSource(this._result);

  final Future<List<UserModel>> Function() _result;

  @override
  Future<List<UserModel>> fetchUsers() => _result();
}

ProviderContainer _container(UserRemoteDataSource dataSource) {
  final container = ProviderContainer(
    overrides: [userRemoteDataSourceProvider.overrideWithValue(dataSource)],
    // Disable Riverpod's automatic retry so failures surface immediately.
    retry: (retryCount, error) => null,
  );
  addTearDown(container.dispose);
  return container;
}

void main() {
  test('loads users from the data source', () async {
    final container = _container(
      _FakeDataSource(
        () async => const [UserModel(id: 1, name: 'A', email: 'a@x.io')],
      ),
    );

    final users = await container.read(usersProvider.future);

    expect(users.single.name, 'A');
  });

  test('maps data source errors to a Failure', () async {
    final container = _container(
      _FakeDataSource(() async => throw const AppException('boom')),
    );
    final subscription = container.listen(usersProvider, (previous, next) {});
    addTearDown(subscription.close);

    await expectLater(
      container.read(usersProvider.future),
      throwsA(isA<Failure>()),
    );
    expect(container.read(usersProvider).error, isA<Failure>());
  });

  test('refresh recovers after an error', () async {
    var fail = true;
    final container = _container(
      _FakeDataSource(() async {
        if (fail) throw const AppException('boom');
        return const [UserModel(id: 2, name: 'B', email: 'b@x.io')];
      }),
    );
    final subscription = container.listen(usersProvider, (previous, next) {});
    addTearDown(subscription.close);

    await expectLater(container.read(usersProvider.future), throwsA(anything));
    fail = false;
    await container.read(usersProvider.notifier).refresh();

    expect(container.read(usersProvider).value?.single.name, 'B');
  });

  test('UserModel round-trips JSON and rejects malformed input', () {
    const json = {'id': 1, 'name': 'A', 'email': 'a@x.io'};
    expect(UserModel.fromJson(json).toJson(), json);
    expect(() => UserModel.fromJson(const {'id': '1'}), throwsFormatException);
  });
}
''';
}
