/// Template builders for the generated project's tests.
///
/// Every generated test starts with [header] so `clean` can recognise it.
class TestTemplate {
  TestTemplate._();

  /// First line of every generated test file.
  static const String header = '// Generated by flutter_project_builder.';

  /// `test/widget_test.dart`: app smoke test (replaces the counter test
  /// created by `flutter create`, which no longer matches `lib/main.dart`).
  static String appTest(String package, {required bool samples}) {
    final sampleTests = samples
        ? r'''

  testWidgets('counter sample increments', (tester) async {
    await tester.pumpWidget(const ProviderScope(child: MyApp()));
    await tester.pumpAndSettle();

    await tester.tap(find.text('Counter'));
    await tester.pumpAndSettle();
    expect(find.text('0'), findsOneWidget);

    await tester.tap(find.byTooltip('Increment'));
    await tester.pump();
    expect(find.text('1'), findsOneWidget);
  });

  testWidgets('users sample loads mock users', (tester) async {
    await tester.pumpWidget(const ProviderScope(child: MyApp()));
    await tester.pumpAndSettle();

    await tester.tap(find.text('Users'));
    // Let the route build; the mock data source is still loading (300ms).
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 100));
    expect(find.byType(CircularProgressIndicator), findsOneWidget);

    await tester.pumpAndSettle();
    expect(find.text('Ada Lovelace'), findsOneWidget);
  });'''
        : '';
    final materialImport =
        samples ? "import 'package:flutter/material.dart';\n" : '';
    return '''
$header
${materialImport}import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';

import 'package:$package/app.dart';
import 'package:$package/core/constants/app_strings.dart';

void main() {
  testWidgets('app starts on the home page', (tester) async {
    await tester.pumpWidget(const ProviderScope(child: MyApp()));
    await tester.pumpAndSettle();

    expect(find.text(AppStrings.appName), findsOneWidget);
  });$sampleTests
}
''';
  }

  /// `test/core/widgets/app_button_test.dart`.
  static String appButtonTest(String package) => '''
$header
