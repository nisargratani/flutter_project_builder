import 'package:path/path.dart' as p;

import '../cli/cli_logger.dart';
import '../config/constants.dart';
import '../config/project_config.dart';
import '../utils/file_utils.dart';
import '../utils/pubspec_utils.dart';

import 'config_generator.dart';
import 'core_generator.dart';
import 'feature_generator.dart';
import 'localization_generator.dart';
import 'network_generator.dart';
import 'router_generator.dart';
import 'service_generator.dart';
import 'storage_generator.dart';
import 'test_generator.dart';
import 'theme_generator.dart';
import 'widget_generator.dart';

/// Orchestrates the generation of the entire Flutter project architecture.
class ProjectGenerator {
  ProjectGenerator({
    required this.projectPath,
    required this.config,
    required this.logger,
  });

  /// The path to the project.
  final String projectPath;

  /// The project configuration.
  final ProjectConfig config;

  /// The CLI logger.
  final CliLogger logger;

  /// Generates the project architecture.
  ///
  /// If [upgradeMode] is true, it only regenerates core files and skips
  /// features, routing, config files, and tests to avoid overwriting user logic.
  Future<void> generate({bool upgradeMode = false}) async {
    final totalSteps = upgradeMode ? 6 : 12;
    logger.startProgress(total: totalSteps);

    // 1. Dependencies
    logger.step('Updating dependencies...');
    PubspecUtils.addDependencies(
      projectPath,
      PackageConstants.generatedDependencies,
    );
    PubspecUtils.addDependencies(
      projectPath,
      PackageConstants.generatedDevDependencies,
      isDev: true,
    );

    if (config.localization) {
      PubspecUtils.addLocalizationConfig(projectPath);
    }

    // Initialize individual generators
    final coreGen = CoreGenerator(projectPath: projectPath, config: config);
    final themeGen = ThemeGenerator(projectPath: projectPath, config: config);
    final widgetGen = WidgetGenerator(projectPath: projectPath, config: config);
    final serviceGen =
        ServiceGenerator(projectPath: projectPath, config: config);
    final networkGen =
        NetworkGenerator(projectPath: projectPath, config: config);
    final storageGen =
        StorageGenerator(projectPath: projectPath, config: config);
    final routerGen = RouterGenerator(projectPath: projectPath, config: config);
    final l10nGen =
        LocalizationGenerator(projectPath: projectPath, config: config);
    final featureGen = FeatureGenerator(
        projectPath: projectPath, config: config, logger: logger);
    final configGen = ConfigGenerator(projectPath: projectPath, config: config);
    final testGen = TestGenerator(projectPath: projectPath, config: config);

    // 2. Core Infrastructure
    logger.step('Generating Core infrastructure...');
    await coreGen.generate();
    await serviceGen.generate();

    // 3. Theme
    logger.step('Generating Theme...');
    await themeGen.generate();

    // 4. Widgets
    logger.step('Generating UI Widgets...');
    await widgetGen.generate();

    // 5. Network (if enabled)
    if (config.dio) {
      logger.step('Generating Network layer...');
      await networkGen.generate();
    }

    // 6. Storage (if enabled)
    if (config.hive) {
      logger.step('Generating Storage layer...');
      await storageGen.generate();
    }

    // Stop here if we're just upgrading core files
    if (upgradeMode) {
      _writeMarker();
      logger.completeProgress();
      return;
    }

    // 7. Router
    logger.step('Generating Router...');
    await routerGen.generate();

    // 8. Localization (if enabled)
    if (config.localization) {
      logger.step('Generating Localization...');
      await l10nGen.generate();
    }

    // 9. Sample Features
    if (config.sampleFeatures) {
      logger.step('Generating Sample features...');
      await featureGen.generateCounterSample();
      await featureGen.generateUsersSample();
    } else {
      // Just create the empty folder structure
      logger.step('Creating feature folder structure...');
      FileUtils.createGitKeep(p.join(projectPath, 'lib', 'features'));
    }

    // 10. Main Configs / Flavors
    logger.step('Generating main files and config...');
    await configGen.generate();

    // 11. Tests
    logger.step('Generating Test templates...');
    await testGen.generate();

    // 12. Documentation
    logger.step('Generating documentation...');
    _writeMarker();

    logger.completeProgress();
  }

  void _writeMarker() {
    FileUtils.createFile(
      p.join(projectPath, 'lib', PackageConstants.generatedMarkerFile),
      '# Generated by flutter_project_builder v${PackageConstants.version}',
    );
  }
}
